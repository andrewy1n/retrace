#!/usr/bin/env python3
"""Open or update the pull request that ships a proposal, from its replay results.

  ship_pr.py analysis/proposals/<id> [--prefix final1] [--dry-run] [--base main]

Finds each candidate job in runs/jobs/ whose arm names the proposal, pairs it with the control job that ran the same
tasks, and writes the description from runs/results/ and runs/primitives/. With no `pr_url` in proposal.json it
creates the branch retrace/<id>, sets `pr_url` (and the proposal.json hash in FROZEN.md when there is one), pushes, and
opens the pull request. With a `pr_url` it replaces that pull request's description. --dry-run prints the description.
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import report

REPO = Path(__file__).resolve().parents[2]
SIGNAL_TEXT = {
    "calls_before_first_edit": f"Runs with more than {report.CALLS_BEFORE_FIRST_EDIT_LIMIT} calls before the first edit",
    "whole_suite_tests": "Runs with a whole-suite test run over 60 s",
    "skipped_verification": "Runs that end with no test after the last edit",
}
SPLIT_TEXT = {"heldout": "Held-out tasks", "regression": "Regression tasks"}
FOOTER = "Generated by Retrace (`recorder/replay/ship_pr.py`) from `runs/results/` and `runs/primitives/`."


def fail(msg):
    sys.exit(f"error: {msg}")


def sh(*cmd, cwd=REPO):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if r.returncode:
        fail(f"{' '.join(cmd)}: {(r.stderr or r.stdout).strip()}")
    return r.stdout.strip()


def find_pairs(root, proposal_path, prefix):
    jobs = [json.loads(p.read_text()) for p in sorted((root / "runs" / "jobs").glob(f"{prefix}*.json"))]
    pairs = []
    for cand in jobs:
        if cand["arm"].get("kind") != "candidate" or cand["arm"].get("path") != proposal_path:
            continue
        same = [j for j in jobs if j["arm"].get("kind") == "control" and set(j["task_ids"]) == set(cand["task_ids"])
                and j["reruns"] == cand["reruns"] and j["model"] == cand["model"]]
        if len(same) > 1:
            fail(f"{cand['job_id']} matches {len(same)} control jobs on the same tasks, narrow --prefix")
        if same:
            pairs.append((same[0], cand))
    if not pairs:
        fail(f"no candidate job with a control job in runs/jobs/{prefix}*.json names {proposal_path}")
    return pairs


def split_name(job_id):
    for key, text in SPLIT_TEXT.items():
        if key in job_id:
            return text
    return job_id


def interval(m, lo, hi, scale=100, unit=" points"):
    return f"{scale * m:+.1f}{unit} (95% interval {scale * lo:+.1f} to {scale * hi:+.1f})"


def split_stats(control, cand, primitives, signal):
    ct, ot = report.by_task(control), report.by_task(cand)
    common = sorted(set(ct) & set(ot))
    out = {"tasks": len(common), "trials": (len(control), len(cand)),
           "passed": (sum(r["passed"] for r in control), sum(r["passed"] for r in cand)),
           "credits_per_trial": tuple(sum(r["cost_credits"] or 0 for r in rs) / len(rs) for rs in (control, cand)),
           "harm": sum(all(r["passed"] for r in ct[t]) and not all(r["passed"] for r in ot[t]) for t in common),
           "repo_tests_error": tuple(sum(r["proxies"]["repo_tests"]["status"] == "error" for r in rs) for rs in (control, cand))}
    logs = [(report.task_log_credits(ct[t]), report.task_log_credits(ot[t])) for t in common]
    out["credit_ratio"] = report.bootstrap_mean([o - c for c, o in logs if c is not None and o is not None])
    if signal:
        flags = {a: [f for f in (report.run_has_signal(r, primitives, signal) for r in rs) if f is not None]
                 for a, rs in (("c", control), ("o", cand))}
        out["signal_runs"] = tuple((sum(flags[a]), len(flags[a])) for a in ("c", "o"))
        per = {(t, a): [f for f in (report.run_has_signal(r, primitives, signal) for r in rs) if f is not None]
               for t in common for a, rs in (("c", ct[t]), ("o", ot[t]))}
        both = [t for t in common if per[t, "c"] and per[t, "o"]]
        out["signal_diff"] = report.bootstrap_mean([sum(per[t, "o"]) / len(per[t, "o"]) - sum(per[t, "c"]) / len(per[t, "c"])
                                                    for t in both])
    return out


def overlay_files(proposal_dir):
    files = [p for p in sorted(proposal_dir.rglob("*")) if p.is_file() and p.relative_to(proposal_dir).parts[0] in (".factory", "AGENTS.md")]
    return [p.relative_to(proposal_dir).as_posix() for p in files]


def summary(proposal_dir, files):
    for f in files:
        if "/hooks/" in f:
            lines = (proposal_dir / f).read_text().splitlines()[1:]
            block = []
            for line in lines:
                if not line.startswith("#"):
                    break
                block.append(line.lstrip("# ").rstrip())
            if block:
                return " ".join(block)
    return "See the files below."


def build_body(proposal_dir, proposal, pairs, results_dir, primitives):
    files = overlay_files(proposal_dir)
    target = proposal.get("cost_pattern") or proposal.get("failure_type")
    signal = report.SIGNALS.get(target)
    stats = []
    for control_job, cand_job in pairs:
        control = report.load_arm(control_job["job_id"], results_dir)
        cand = report.load_arm(cand_job["job_id"], results_dir)
        stats.append((cand_job, control, cand, split_stats(control, cand, primitives, signal)))
    everything = [r for _, c, o, _ in stats for r in c + o]
    models = sorted({r["model"] for r in everything})
    versions = sorted({r["droid_version"] for r in everything})
    datasets = sorted({j["dataset"] for j, *_ in stats})
    reruns = sorted({j["reruns"] for j, *_ in stats})

    lines = ["## Summary", "", summary(proposal_dir, files), "",
             f"Target: `{target}`. Change type: {proposal['change_type'].replace('_', ' ')}.", "",
             "Files:", ""] + [f"- `{proposal['path']}/{f}`" for f in files] + [
             "", "## Results", "",
             f"Fresh runs on {', '.join(datasets)} with {', '.join(models)} on Droid {', '.join(versions)}, "
             f"{', '.join(map(str, reruns))} reruns per task. Baseline is unmodified Droid. "
             "\"With change\" installs the files above before the session starts.", ""]
    head = ["", *(f"{split_name(j['job_id'])}, {side}" for j, *_ in stats for side in ("baseline", "with change"))]
    rows = [("Tasks / trials", lambda s: (f"{s['tasks']} / {s['trials'][0]}", f"{s['tasks']} / {s['trials'][1]}")),
            ("Passed", lambda s: tuple(f"{p} of {n}" for p, n in zip(s["passed"], s["trials"]))),
            ("Credits per trial", lambda s: tuple(f"{c:,.0f}" for c in s["credits_per_trial"]))]
    if signal:
        rows.insert(1, (SIGNAL_TEXT[target], lambda s: tuple(f"{k} of {n}" for k, n in s["signal_runs"])))
    lines.append("| " + " | ".join(head) + " |")
    lines.append("|" + "---|" * len(head))
    for label, cells in rows:
        vals = [v for *_, s in stats for v in cells(s)]
        lines.append("| " + " | ".join([label, *vals]) + " |")
    lines.append("")
    for j, _, _, s in stats:
        name = split_name(j["job_id"])
        if signal:
            lines.append(f"- {name}: {SIGNAL_TEXT[target].lower()}, paired by task: {interval(*s['signal_diff'])}.")
        m, lo, hi = s["credit_ratio"]
        lines.append(f"- {name}: credits, ratio with change to baseline: {report.ratio(m)} (95% interval {report.ratio(lo)} to {report.ratio(hi)}) over {s['tasks']} tasks.")
        lines.append(f"- {name}: tasks that pass every baseline rerun and fail a rerun with the change: {s['harm']}.")
    lines += ["", "## Limitations", ""]
    for j, _, _, s in stats:
        name = split_name(j["job_id"])
        if s["tasks"] < 10:
            lines.append(f"- {name}: {s['tasks']} tasks. Bootstrap intervals say little at this size.")
        near = [p / n for p, n in zip(s["passed"], s["trials"])]
        if min(near) >= 0.9:
            lines.append(f"- {name}: pass rate is near 100% in both runs, so it cannot separate them.")
        if any(s["repo_tests_error"]):
            lines.append(f"- {name}: the repo test check gave no verdict in {s['repo_tests_error'][0]} baseline and {s['repo_tests_error'][1]} changed trials.")
    lines += [f"- {len(everything)} trials on one model. The tasks come from {len({r['task_id'].split('__')[0] for r in everything})} repositories.",
              "", "## Rollback", "",
              f"Remove {', '.join(f'`{f}`' for f in files)} from the repository that adopted them.", "", FOOTER]
    return "\n".join(lines) + "\n"


def refresh_frozen(proposal_dir):
    frozen = proposal_dir / "FROZEN.md"
    if not frozen.exists():
        return
    digest = hashlib.sha256((proposal_dir / "proposal.json").read_bytes()).hexdigest()
    text = re.sub(r"(\| `proposal\.json`[^|]*\| `)[0-9a-f]{64}(` \|)", rf"\g<1>{digest}\g<2>", frozen.read_text())
    if "(with `pr_url`)" not in text:
        text = text.replace("| `proposal.json` |", "| `proposal.json` (with `pr_url`) |")
    frozen.write_text(text)


def set_pr_url(proposal_dir, proposal, url):
    proposal["pr_url"] = url
    (proposal_dir / "proposal.json").write_text(json.dumps(proposal, indent=2) + "\n")
    refresh_frozen(proposal_dir)


def open_pr(proposal_dir, proposal, body_file, base):
    rel = proposal_dir.relative_to(REPO).as_posix()
    if sh("git", "status", "--porcelain", "--", rel):
        fail(f"{rel} has uncommitted changes")
    start = sh("git", "rev-parse", "--abbrev-ref", "HEAD")
    nxt = int(sh("gh", "api", "repos/{owner}/{repo}/issues?state=all&per_page=1&direction=desc", "--jq", ".[0].number") or 0) + 1
    url_base = sh("gh", "repo", "view", "--json", "url", "--jq", ".url") + "/pull/"
    branch = f"retrace/{proposal['proposal_id']}"
    title = f"feat(proposals): ship the {proposal['proposal_id']} change"
    sh("git", "switch", "-c", branch, base)
    try:
        set_pr_url(proposal_dir, proposal, f"{url_base}{nxt}")
        sh("git", "commit", "-q", "-m", f"feat(proposals): link the {proposal['proposal_id']} pull request", "--", rel)
        sh("git", "push", "-q", "-u", "origin", branch)
        url = sh("gh", "pr", "create", "--base", base, "--head", branch, "--title", title, "--body-file", str(body_file))
        if url != f"{url_base}{nxt}":
            set_pr_url(proposal_dir, proposal, url)
            sh("git", "commit", "-q", "-m", f"fix(proposals): correct the {proposal['proposal_id']} pull request link", "--", rel)
            sh("git", "push", "-q")
    finally:
        sh("git", "switch", "-q", start)
    return url


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("proposal", help="proposal directory, relative to the repo")
    ap.add_argument("--base", default="main")
    ap.add_argument("--prefix", default="", help="only jobs whose id starts with this, such as final1")
    ap.add_argument("--root", default=str(REPO), help="repo root")
    ap.add_argument("--dry-run", action="store_true", help="print the description, change nothing")
    args = ap.parse_args(argv)

    root = Path(args.root).resolve()
    proposal_dir = root / args.proposal
    proposal = json.loads((proposal_dir / "proposal.json").read_text())
    pairs = find_pairs(root, proposal["path"], args.prefix)
    body = build_body(proposal_dir, proposal, pairs, root / "runs" / "results", root / "runs" / "primitives")
    if args.dry_run:
        sys.stdout.write(body)
        return
    body_file = root / "runs" / "private" / f"pr-{proposal['proposal_id']}.md"
    body_file.parent.mkdir(parents=True, exist_ok=True)
    body_file.write_text(body)
    if proposal.get("pr_url"):
        sh("gh", "pr", "edit", proposal["pr_url"], "--body-file", str(body_file))
        print(f"updated {proposal['pr_url']}")
    else:
        print(f"opened {open_pr(proposal_dir, proposal, body_file, args.base)}")


if __name__ == "__main__":
    main()
