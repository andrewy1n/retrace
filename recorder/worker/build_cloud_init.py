#!/usr/bin/env python3
"""Regenerate cloud-init.yaml from scripts/, ../capture/ and ../replay/ (keeps one source of truth). Run: python3 build_cloud_init.py"""
from pathlib import Path

HERE = Path(__file__).parent
SCRIPTS = [
    ("scripts/prepull.sh", "prepull.sh"),
    ("scripts/run_trial.sh", "run_trial.sh"),
    ("scripts/run_job.sh", "run_job.sh"),
    ("scripts/grade.sh", "grade.sh"),
    ("scripts/retrace_job.py", "retrace_job.py"),
    ("scripts/tiger_sink.py", "tiger_sink.py"),
    ("../replay/run_checkpoint.sh", "replay/run_checkpoint.sh"),
    ("../replay/docker-droid.sh", "replay/docker-droid.sh"),
    ("../replay/restore.sh", "replay/restore.sh"),
    ("../replay/fork.mjs", "replay/fork.mjs"),
    ("../replay/package.json", "replay/package.json"),
    ("../replay/package-lock.json", "replay/package-lock.json"),
    ("../capture/snapshot.sh", "capture/snapshot.sh"),
    ("../capture/hook.sh", "capture/hook.sh"),
    ("../capture/hook.py", "capture/hook.py"),
    ("../capture/trace.py", "capture/trace.py"),
]

HEADER = """#cloud-config
# Retrace replay/grading worker. Target: Vultr vc2-16c-64gb, region sjc, Ubuntu 24.04 LTS x64 (os id 2284).
# Generated by build_cloud_init.py from scripts/, ../capture/ and ../replay/ -- edit those, then regenerate.
# No secrets here: export FACTORY_API_KEY (and optional VULTR_INFERENCE_API_KEY, HF_TOKEN) after SSH-ing in.
# Progress: tail -f /var/log/cloud-init-output.log ; done when /opt/retrace/READY exists.

package_update: true
package_upgrade: false
packages:
  - ca-certificates
  - curl
  - git
  - jq
  - ripgrep
  - xdg-utils
  - python3
  - python3-venv
  - python3-pip
  - build-essential
  - tmux
  - htop

users:
  - default
  - name: retrace
    gecos: Retrace worker
    shell: /bin/bash
    groups: [sudo]
    sudo: "ALL=(ALL) NOPASSWD:ALL"

write_files:
  - path: /etc/sysctl.d/90-retrace.conf
    content: |
      fs.inotify.max_user_watches = 1048576
      fs.inotify.max_user_instances = 8192
      fs.file-max = 2097152
      vm.max_map_count = 262144
  - path: /etc/security/limits.d/90-retrace.conf
    content: |
      *    soft nofile 1048576
      *    hard nofile 1048576
      root soft nofile 1048576
      root hard nofile 1048576
  - path: /etc/docker/daemon.json
    content: |
      {
        "default-ulimits": {"nofile": {"Name": "nofile", "Soft": 1048576, "Hard": 1048576}},
        "log-driver": "json-file",
        "log-opts": {"max-size": "50m", "max-file": "3"},
        "max-concurrent-downloads": 6
      }
  - path: /etc/profile.d/retrace.sh
    content: |
      export PATH="/opt/retrace/venv/bin:/opt/retrace:$PATH"
      export SWEBENCH_DATASET="SWE-bench/SWE-bench_Verified"
      # Set secrets yourself, e.g.: export FACTORY_API_KEY=fk-...   (never commit them)
"""

FOOTER = """
runcmd:
  - [sysctl, --system]
  - [bash, -c, "curl -fsSL https://get.docker.com | sh"]
  - [systemctl, enable, --now, docker]
  - [bash, -c, "usermod -aG docker retrace; for u in ubuntu linuxuser; do id $u >/dev/null 2>&1 && usermod -aG docker $u; done; true"]
  - [bash, -c, "mkdir -p /home/retrace/.ssh && cp /root/.ssh/authorized_keys /home/retrace/.ssh/ 2>/dev/null; chown -R retrace:retrace /home/retrace/.ssh; chmod 700 /home/retrace/.ssh; true"]
  - [bash, -c, "curl -fsSL https://deb.nodesource.com/setup_lts.x | bash - && apt-get install -y nodejs"]
  - [bash, -c, "cd /opt/retrace/replay && npm ci --omit=dev --no-audit --no-fund"]
  - [bash, -c, "export HOME=/root && curl -fsSL https://app.factory.ai/cli | sh && install -m 0755 /root/.local/bin/droid /usr/local/bin/droid"]
  - [bash, -c, "python3 -m venv /opt/retrace/venv && /opt/retrace/venv/bin/pip install --upgrade pip && /opt/retrace/venv/bin/pip install 'swebench==5.0.2' datasets jsonschema 'psycopg[binary]'"]
  - [bash, -c, "git clone https://github.com/andrewy1n/retrace.git /opt/retrace/repo"]
  - [bash, -c, "git config --system --add safe.directory /opt/retrace/repo"]
  - [bash, -c, "mkdir -p /opt/retrace/runs /opt/retrace/logs && chown -R retrace:retrace /opt/retrace"]
  - [bash, -c, "docker --version; node --version; droid --version; /opt/retrace/venv/bin/python -c 'import swebench; print(\\"swebench\\", swebench.__version__)'"]
  - [bash, -c, "date -Is > /opt/retrace/READY"]

final_message: "Retrace worker ready after $UPTIME s. See /var/log/cloud-init-output.log"
"""

def block(src: str, dest: str) -> str:
    body = (HERE / src).read_text()
    ind = "".join("      " + l if l.strip() else "\n" for l in body.splitlines(keepends=True))
    ind = "\n".join(l if l.strip() else "" for l in ind.split("\n"))
    return f"  - path: /opt/retrace/{dest}\n    permissions: '0755'\n    content: |\n{ind}"

out = HEADER + "".join(block(*s) for s in SCRIPTS) + FOOTER
(HERE / "cloud-init.yaml").write_text(out)
print("wrote", HERE / "cloud-init.yaml")
